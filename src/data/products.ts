export function buildAffiliateUrl(
  product: Product,
  partner: AffiliatePartner,
  config: AffiliateConfig
): string {
  if (partner === 'daraz') {
    const query = encodeURIComponent(product.darazSearchTerm);
    const affId = encodeURIComponent(config.darazAffiliateId.trim() || 'zayr_daraz_pk');
    return `https://www.daraz.pk/catalog/?q=${query}&utm_source=affiliate&utm_medium=referral&aff_id=${affId}&sub_id=${encodeURIComponent(product.id)}`;
  }

  const query = encodeURIComponent(product.amazonSearchTerm);
  const tag = encodeURIComponent(config.amazonAssociateTag.trim() || 'zayrselect-20');
  return `https://www.amazon.com/s?k=${query}&tag=${tag}&linkCode=ll2&ref_=as_li_ss_tl`;
}

